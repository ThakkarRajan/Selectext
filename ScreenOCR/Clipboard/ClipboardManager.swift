import AppKit

struct ClipboardManager {
    /// Change count right after ScreenOCR's own last write, so the monitor can ignore it.
    @MainActor static var lastOwnChangeCount = -1

    @MainActor
    @discardableResult
    func copy(text: String) -> Bool {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let copied = pasteboard.setString(text, forType: .string)
        Self.lastOwnChangeCount = pasteboard.changeCount
        return copied
    }
}

/// Records text the user copies in other apps. macOS has no clipboard-change
/// notification, so the change count is polled.
@MainActor
final class ClipboardMonitor {
    private let onCopy: (String) -> Void
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Marker types from nspasteboard.org that password managers and similar apps set.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]
    private static let maxLength = 20_000

    init(onCopy: @escaping (String) -> Void) {
        self.onCopy = onCopy
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard changeCount != ClipboardManager.lastOwnChangeCount else { return }
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        guard let text = pasteboard.string(forType: .string) else { return }

        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, text.count <= Self.maxLength else { return }
        onCopy(text)
    }
}
